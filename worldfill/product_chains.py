"""
Step 44 part 4 (E5 part D): chains and workplaces — what each product is made from, and who
makes it.

The plan's part D asks for "workplaces and chains: farms, mines, forges, looms, presses turning
inputs into products each day". Part B built the machinery for the first half and left it nearly
empty: of 529 products only **38 carry any inputs at all**, and none of the 397 part C products
does, even though 290 of them were defined by a parent. The survey for this step found the same
hole from the other side: **"there are no makers — no workplace turns an input into an output."**

So this module supplies three things, none of them a date:

  * **inputs** — what a product is made from. For the 290 part C children the parent already
    *is* the input: flour is made from wheat, cheese from milk, a sword from bronze. Writing it
    down is what lets the atlas say "there is no wheat here to make flour" instead of silently
    having flour. Where a product needs something beyond its parent (bread needs fire as well as
    grain, a rifle needs gunpowder as well as iron) that is listed too.
  * **work** — which of the **12 kinds of work** in `jobs.json.gz` makes it: farming, herding,
    foraging, craft, miner, trade, service, transport, soldier, clergy, official, scholar. That
    register already says, for any place and year, what share of people do each — so naming the
    work is what turns "iron is made here" into "one man in fifty here is a smith".
  * **workplace** — where the work happens: a farm, a mine, a forge, a loom, a kiln, a press.
    This is the thing the mod has never had, and it is what D16 needs for its missing makers.

A family gives the default; a product overrides it. Nothing here invents a year.
"""

