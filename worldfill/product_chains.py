def check_against(products):
    """Every id named here must be a product in the pack. Part 3 dropped several rows, and this
    is what catches a table still pointing at them."""
    ids = {p["id"] for p in products}
    problems = []
    for pid in sorted(PRODUCT_WORK):
        if pid not in ids:
            problems.append(f"PRODUCT_WORK names '{pid}', which is not a product")
    for pid in sorted(EXTRA_INPUTS):
        if pid not in ids:
            problems.append(f"EXTRA_INPUTS names '{pid}', which is not a product")
        for group in EXTRA_INPUTS[pid]:
            for i in group:
                if i not in ids:
                    problems.append(f"EXTRA_INPUTS for '{pid}' names '{i}', which is not a product")
    return problems


def work_of(product_id, family):
    """(work, workplace) for a product: its own override, else its family's default."""
    if product_id in PRODUCT_WORK:
        return PRODUCT_WORK[product_id]
    return FAMILY_WORK.get(family, ("craft", "workshop"))


