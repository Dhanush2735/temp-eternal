package org.apache.logging.log4j;

// STUB for the step-31 harness only: log4j is not on the classpath outside a
// Forge build. Silent, so the real index/estimator sources compile unchanged.
public final class Logger {
    public void trace(String m) {}
    public void debug(String m) {}
    public void info(String m) {}
    public void warn(String m) {}
    public void error(String m) {}
    public void trace(String m, Object a) {}
    public void debug(String m, Object a) {}
    public void info(String m, Object a) {}
    public void warn(String m, Object a) {}
    public void error(String m, Object a) {}
    public void trace(String m, Object a, Object b) {}
    public void debug(String m, Object a, Object b) {}
    public void info(String m, Object a, Object b) {}
    public void warn(String m, Object a, Object b) {}
    public void error(String m, Object a, Object b) {}
    public void trace(String m, Object... a) {}
    public void debug(String m, Object... a) {}
    public void info(String m, Object... a) {}
    public void warn(String m, Object... a) {}
    public void error(String m, Object... a) {}
    public void trace(String m, Throwable t) {}
    public void debug(String m, Throwable t) {}
    public void info(String m, Throwable t) {}
    public void warn(String m, Throwable t) {}
    public void error(String m, Throwable t) {}
    public boolean isTraceEnabled() { return false; }
    public boolean isDebugEnabled() { return false; }
    public boolean isInfoEnabled() { return false; }
    public boolean isWarnEnabled() { return false; }
    public boolean isErrorEnabled() { return false; }
}
